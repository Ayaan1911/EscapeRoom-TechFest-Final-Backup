import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { initialProgress } from "../src/lib/game/engine";
import { hashPassword } from "../src/lib/password.mjs";
import { inboxAnswers, tamperAnswer } from "./fixtures/inbox";
import { NextRequest } from "next/server";
import { trailAnswers, trailTamper } from "./fixtures/trail";

const jar = vi.hoisted(() => new Map<string,string>());
vi.mock("next/headers", () => ({ cookies: async () => ({ get: (key: string) => jar.has(key) ? { value: jar.get(key) } : undefined, set: (key: string,value: string) => jar.set(key,value), delete: (key: string) => jar.delete(key) }) }));

// Opt in only after installing Prisma and generating the client; always uses a fresh temporary DB.
describe.runIf(process.env.GHOST_DB_TEST === "1")("Prisma persistence and session integration", () => {
  let folder: string;
  let db: typeof import("../src/lib/db").db;
  let auth: typeof import("../src/lib/auth");
  let service: typeof import("../src/lib/game/service");
  const code = "temporary-test-access-only";
  beforeAll(async () => {
    folder = mkdtempSync(join(tmpdir(), "ghost-test-"));
    process.env.DATABASE_URL = `file:${join(folder,"test.db").replaceAll("\\","/")}`;
    process.env.ADMIN_ACCESS_HASH = hashPassword(code);
    process.env.APP_ORIGIN = "http://127.0.0.1:3000";
    ({ db } = await import("../src/lib/db"));
    auth = await import("../src/lib/auth");
    service = await import("../src/lib/game/service");
    for (const statement of readFileSync("prisma/migrations/202611170001_engine/migration.sql","utf8").split(";").filter(s=>s.trim())) await db.$executeRawUnsafe(statement);
    for (const id of ["A","B"]) await db.team.create({ data: { id, name:id, participants:JSON.stringify(["One","Two","Three"]), codeHash:hashPassword(code), variant:"A", progress:JSON.stringify(initialProgress()) } });
  });
  afterAll(async () => { if(db) await db.$disconnect(); if(folder) rmSync(folder, { recursive:true, force:true }); });
  it("logs in, isolates team identity, survives reads and invalidates logout", async () => {
    expect(await auth.session("team")).toBeNull();
    expect(await auth.login("team","A","wrong-code")).toBe(false);
    expect(await auth.login("team","A",code)).toBe(true);
    expect((await auth.session("team"))?.teamId).toBe("A");
    expect(await auth.session("admin")).toBeNull();
    expect((await auth.session("team"))?.teamId).toBe("A");
    const token = jar.get(auth.cookieName)!;
    await auth.logout(); jar.set(auth.cookieName,token);
    expect(await auth.session("team")).toBeNull(); jar.clear();
  });
  it("protects admin and participant APIs", async () => {
    const game = await import("../src/app/api/game/route");
    const scores = await import("../src/app/api/admin/scores/route");
    expect((await game.GET()).status).toBe(401);
    expect((await scores.GET()).status).toBe(401);
    await auth.login("team","A",code);
    expect((await scores.GET()).status).toBe(401);
    const data = await (await game.GET()).json(); expect(data.id).toBe("A"); expect(data.codeHash).toBeUndefined();
    await auth.logout();
    await auth.login("admin","organizer",code);
    expect(await auth.session("team")).toBeNull(); expect((await scores.GET()).status).toBe(200);
    await auth.logout();
  });
  it("persists shared start, audited override and rejects duplicate and late attempts", async () => {
    await service.roundState(); await service.control("start");
    const a = await service.teamState("A"), b=await service.teamState("B");
    expect(a.round.deadline?.getTime()).toBe(b.round.deadline?.getTime());
    expect(a.round.deadline!.getTime()-a.round.startsAt!.getTime()).toBe(3600000);
    await expect(service.control("start")).rejects.toThrow();
    await service.control("unlock","A","Organizer confirmed a stuck workspace");
    expect((await service.teamState("A")).current).toBe(1);
    expect((await service.teamState("A")).score).toBe(0);
    expect((await service.mutateTeam("A",0,"submit",{})).error).toBeDefined();
    expect(await db.auditLog.count({where:{action:"unlock"}})).toBe(1);
    const { validators } = await import("../src/lib/game/validators");
    const registeredTrail = validators[1];
    // Test-only fixture, never a real chapter answer key.
    validators[1] = { validate: () => ({ correct:true, points:25, tamperDetected:true }), hints:["Test hint one","Test hint two"] };
    expect((await service.mutateTeam("A",1,"hint",null)).hint).toBe("Test hint one");
    expect((await service.mutateTeam("A",1,"hint",null)).hint).toBe("Test hint two");
    expect((await service.mutateTeam("A",1,"hint",null)).error).toBeDefined();
    expect((await service.mutateTeam("A",1,"submit",{})).accepted).toBe(true);
    expect((await service.teamState("A")).score).toBe(21);
    expect((await service.mutateTeam("A",1,"submit",{})).error).toBeDefined();
    await db.$disconnect();
    expect((await service.teamState("A")).current).toBe(2);
    validators[1] = registeredTrail;
    await service.control("stop"); expect((await service.teamState("A")).status).toBe("finished");
    expect((await service.mutateTeam("A",2,"submit",{})).error).toBeDefined();
    expect(await db.submission.count()).toBe(4);
  });
  it.each(["A", "B", "C"] as const)("plays Inbox %s with isolated saved hints, independent bonus, throttling and completion", async variant => {
    const id = `INBOX-${variant}`;
    await db.team.create({ data: { id, name: id, participants: '[]', codeHash: hashPassword(code), variant, progress: JSON.stringify(initialProgress()) } });
    await db.gameSession.update({ where: { id: 1 }, data: { startsAt: null, deadline: null, endedAt: null } });
    const solution = inboxAnswers[variant];
    expect((await service.mutateTeam(id, 0, "hint", null)).error).toMatch(/not active/);
    expect((await service.mutateTeam(id, 0, "submit", solution)).error).toMatch(/not active/);
    await service.control("start");
    expect((await service.mutateTeam(id, 1, "submit", {})).error).toMatch(/locked/);
    await db.gameSession.update({ where: { id: 1 }, data: { deadline: new Date(Date.now() - 1) } });
    expect((await service.mutateTeam(id, 0, "submit", { ...solution, tamper: tamperAnswer(variant) })).error).toMatch(/not active/);
    expect((await service.mutateTeam(id, 0, "hint", null)).error).toMatch(/not active/);
    expect((await service.teamState(id)).progress.bonus).toBe(0);
    await db.gameSession.update({ where: { id: 1 }, data: { deadline: new Date(Date.now() + 3600000) } });
    await db.submission.updateMany({ where: { teamId: id }, data: { createdAt: new Date(0) } });
    expect((await service.mutateTeam(id, 0, "hint", null)).hint).toBeDefined();
    expect((await service.mutateTeam(id, 0, "hint", null)).hint).toBeDefined();
    expect((await service.mutateTeam(id, 0, "hint", null)).error).toMatch(/Maximum two/);
    expect((await service.teamState(id)).chapterHints[0]).toHaveLength(2);
    const wrong = { ...solution, emailId: "unrelated-email", tamper: tamperAnswer(variant) };
    expect(await service.mutateTeam(id, 0, "submit", wrong)).toEqual({ accepted: false, tamperAwarded: true });
    expect((await service.teamState(id)).progress.bonus).toBe(5);
    expect((await service.teamState(id)).current).toBe(0);
    expect((await service.teamState(id)).score).toBe(0);
    expect((await service.teamState("B")).score).toBe(0);
    await auth.login("team", id, code);
    const game = await import("../src/app/api/game/route");
    const publicState = await (await game.GET()).json();
    expect(publicState.id).toBe(id);
    expect(JSON.stringify(publicState)).not.toMatch(/codeHash|inboxSolution|answerKey|emailId/);
    const origin = process.env.APP_ORIGIN || "http://127.0.0.1:3000";
    const request = (body: unknown) => new NextRequest(`${origin}/api/game`, { method: "POST", headers: { origin, "Content-Type": "application/json" }, body: JSON.stringify(body) });
    expect((await game.POST(request({ action: "submit", chapter: 0, answer: solution, teamId: "B" }))).status).toBe(400);
    const throttled = await game.POST(request({ action: "submit", chapter: 0, answer: solution }));
    expect(throttled.status).toBe(429);
    expect(Number(throttled.headers.get("Retry-After"))).toBeGreaterThan(0);
    await db.submission.updateMany({ where: { teamId: id }, data: { createdAt: new Date(0) } });
    expect(await service.mutateTeam(id, 0, "submit", { kind: "tamper", tamper: tamperAnswer(variant) })).toEqual({ accepted: false, tamperAwarded: false });
    expect(await db.auditLog.count({ where: { actor: id, action: "tamper-alert" } })).toBe(1);
    await db.submission.updateMany({ where: { teamId: id }, data: { createdAt: new Date(0) } });
    expect(await service.mutateTeam(id, 0, "submit", solution)).toEqual({ accepted: true, tamperAwarded: false });
    const saved = await service.teamState(id);
    expect(saved.score).toBe(11); // 15 - 3 - 6 + 5, independently capped.
    expect(saved.current).toBe(1);
    expect(saved.progress.chapters[0].score).toBe(15);
    expect((await service.mutateTeam(id, 0, "submit", solution)).error).toMatch(/locked/);
    expect((await service.mutateTeam(id, 0, "hint", null)).error).toMatch(/locked/);
    await auth.logout(); await auth.login("team", id, code);
    await db.$disconnect();
    expect((await service.teamState((await auth.session("team"))!.teamId!)).score).toBe(11);
    expect((await service.teamState(id)).chapterHints[0]).toHaveLength(2);
    await db.gameSession.update({ where: { id: 1 }, data: { deadline: new Date(Date.now() - 1) } });
    expect((await service.mutateTeam(id, 0, "submit", solution)).error).toMatch(/not active/);
    expect((await service.mutateTeam(id, 0, "hint", null)).error).toMatch(/not active/);
    expect((await service.teamState(id)).score).toBe(11);
    await auth.logout();
  });
  it("never awards Chapter 1 twice for concurrent submissions", async () => {
    const id = "INBOX-RACE";
    await db.team.create({ data: { id, name: id, participants: '[]', codeHash: hashPassword(code), variant: "A", progress: JSON.stringify(initialProgress()) } });
    await db.gameSession.update({ where: { id: 1 }, data: { startsAt: new Date(), deadline: new Date(Date.now() + 3600000), endedAt: null } });
    const tamper = { kind: "tamper", tamper: tamperAnswer("A") };
    await Promise.allSettled([service.mutateTeam(id, 0, "submit", tamper), service.mutateTeam(id, 0, "submit", tamper)]);
    expect((await service.teamState(id)).score).toBe(5);
    expect(await db.auditLog.count({ where: { actor: id, action: "tamper-alert" } })).toBe(1);
    await db.submission.updateMany({ where: { teamId: id }, data: { createdAt: new Date(0) } });
    await Promise.allSettled([service.mutateTeam(id, 0, "submit", inboxAnswers.A), service.mutateTeam(id, 0, "submit", inboxAnswers.A)]);
    expect((await service.teamState(id)).score).toBe(20);
    expect((await service.teamState(id)).progress.bonus).toBe(5);
    expect(await db.submission.count({ where: { teamId: id, accepted: true } })).toBe(1);
  });
  it.each(["A", "B", "C"] as const)("plays Trail %s after actual Inbox completion, preserving the global bonus and saved state", async variant => {
    const id = `TRAIL-${variant}`;
    await db.team.create({ data: { id, name: id, participants: '[]', codeHash: hashPassword(code), variant, progress: JSON.stringify(initialProgress()) } });
    await db.gameSession.update({ where: { id: 1 }, data: { startsAt: null, deadline: null, endedAt: null } });
    const answer = trailAnswers[variant];
    const trail = await import("../src/app/api/game/trail/route");
    const csv = await import("../src/app/api/game/trail/csv/route");
    await auth.login("team", id, code);
    expect((await trail.GET()).status).toBe(403);
    expect((await csv.GET()).status).toBe(403);
    expect((await service.mutateTeam(id, 1, "submit", answer)).error).toMatch(/not active/);
    await service.control("start");
    expect((await service.mutateTeam(id, 1, "hint", null)).error).toMatch(/locked/);
    expect((await service.mutateTeam(id, 1, "submit", answer)).error).toMatch(/locked/);
    expect(await service.mutateTeam(id, 0, "submit", { ...inboxAnswers[variant], ...(variant === "A" ? { tamper: tamperAnswer(variant) } : {}) })).toEqual({ accepted: true, tamperAwarded: variant === "A" });
    expect((await service.teamState(id)).current).toBe(1);
    const response = await trail.GET();
    expect(response.status).toBe(200); expect(response.headers.get("Cache-Control")).toBe("no-store");
    const dataset = await response.json();
    expect(dataset.caseId).toBe(`NEXUS-TRAIL-${variant}`); expect(dataset.rows).toHaveLength(144);
    expect(JSON.stringify(dataset)).not.toMatch(/answerKey|supportingEvidenceIds|trailSolution|tamperDetected/);
    const download = await csv.GET();
    expect(download.headers.get("Content-Disposition")).toContain("attachment");
    expect(await download.text()).toContain('"\'=ANALYST_NOTE(');
    await db.gameSession.update({ where: { id: 1 }, data: { deadline: new Date(Date.now() - 1) } });
    expect((await service.mutateTeam(id, 1, "submit", { kind: "tamper", tamper: trailTamper(variant) })).error).toMatch(/not active/);
    expect((await service.mutateTeam(id, 1, "hint", null)).error).toMatch(/not active/);
    expect((await service.teamState(id)).progress.bonus).toBe(variant === "A" ? 5 : 0);
    await db.gameSession.update({ where: { id: 1 }, data: { deadline: new Date(Date.now() + 3600000) } });
    await db.submission.updateMany({ where: { teamId: id, chapter: 1 }, data: { createdAt: new Date(0) } });
    expect((await service.mutateTeam(id, 1, "hint", null)).hint).toBeDefined();
    expect((await service.mutateTeam(id, 1, "hint", null)).hint).toBeDefined();
    expect((await service.mutateTeam(id, 1, "hint", null)).error).toMatch(/Maximum two/);
    expect((await service.teamState(id)).chapterHints[1]).toHaveLength(2);
    const wrong = { ...answer, account: "unrelated@nexus.example", tamper: trailTamper(variant) };
    expect(await service.mutateTeam(id, 1, "submit", wrong)).toEqual({ accepted: false, tamperAwarded: variant !== "A" });
    expect((await service.teamState(id)).current).toBe(1);
    expect((await service.teamState(id)).score).toBe(11);
    expect((await service.teamState("B")).score).toBe(0);
    const attempts = await db.submission.count({ where: { teamId: id, chapter: 1 } });
    await db.$disconnect();
    expect((await service.mutateTeam(id, 1, "submit", answer)).retryAfter).toBeGreaterThan(0);
    expect(await db.submission.count({ where: { teamId: id, chapter: 1 } })).toBe(attempts);
    await db.submission.updateMany({ where: { teamId: id, chapter: 1 }, data: { createdAt: new Date(0) } });
    expect(await service.mutateTeam(id, 1, "submit", { kind: "tamper", tamper: trailTamper(variant) })).toEqual({ accepted: false, tamperAwarded: false });
    expect(await db.auditLog.count({ where: { actor: id, action: "tamper-alert" } })).toBe(1);
    await db.submission.updateMany({ where: { teamId: id, chapter: 1 }, data: { createdAt: new Date(0) } });
    expect(await service.mutateTeam(id, 1, "submit", answer)).toEqual({ accepted: true, tamperAwarded: false });
    const saved = await service.teamState(id);
    expect(saved.progress.chapters[1].score).toBe(25); expect(saved.score).toBe(36); expect(saved.current).toBe(2);
    expect((await service.mutateTeam(id, 1, "submit", answer)).error).toMatch(/locked/);
    expect((await service.mutateTeam(id, 2, "submit", {})).error).toMatch(/not implemented/);
    await auth.logout(); await auth.login("team", id, code);
    expect((await service.teamState((await auth.session("team"))!.teamId!)).score).toBe(36);
    expect((await trail.GET()).status).toBe(200);
    await auth.logout();
  });
  it("protects Trail JSON and CSV from anonymous, organizer and locked sessions, allowing audited overrides", async () => {
    const trail = await import("../src/app/api/game/trail/route");
    const csv = await import("../src/app/api/game/trail/csv/route");
    expect((await trail.GET()).status).toBe(401); expect((await csv.GET()).status).toBe(401);
    await auth.login("admin", "organizer", code);
    expect((await trail.GET()).status).toBe(401); expect((await csv.GET()).status).toBe(401);
    await auth.logout();
    const id = "TRAIL-OVERRIDE";
    await db.team.create({ data: { id, name: id, participants: '[]', codeHash: hashPassword(code), variant: "B", progress: JSON.stringify(initialProgress()) } });
    await db.gameSession.update({ where: { id: 1 }, data: { startsAt: new Date(), deadline: new Date(Date.now() + 3600000), endedAt: null } });
    await auth.login("team", id, code);
    expect((await trail.GET()).status).toBe(403);
    await service.control("unlock", id, "Verified organizer progression override");
    expect((await service.teamState(id)).progress.chapters[0]).toMatchObject({ score: 0, override: true });
    expect((await service.teamState(id)).current).toBe(1);
    const data = await (await trail.GET()).json();
    expect(data.caseId).toBe("NEXUS-TRAIL-B"); expect(data.rows.every((row: { id: string }) => row.id.startsWith("EV-B-"))).toBe(true);
    expect(await db.auditLog.count({ where: { action: "unlock", detail: { contains: id } } })).toBe(1);
    await auth.logout();
  });
  it("caps concurrent Trail bonus and completion awards using the existing transaction", async () => {
    const id = "TRAIL-RACE";
    await db.team.create({ data: { id, name: id, participants: '[]', codeHash: hashPassword(code), variant: "C", progress: JSON.stringify(initialProgress()) } });
    expect((await service.mutateTeam(id, 0, "submit", inboxAnswers.C)).accepted).toBe(true);
    const tamper = { kind: "tamper", tamper: trailTamper("C") };
    await Promise.allSettled([service.mutateTeam(id, 1, "submit", tamper), service.mutateTeam(id, 1, "submit", tamper)]);
    expect((await service.teamState(id)).progress.bonus).toBe(5);
    expect(await db.auditLog.count({ where: { actor: id, action: "tamper-alert" } })).toBe(1);
    await db.submission.updateMany({ where: { teamId: id, chapter: 1 }, data: { createdAt: new Date(0) } });
    await Promise.allSettled([service.mutateTeam(id, 1, "submit", trailAnswers.C), service.mutateTeam(id, 1, "submit", trailAnswers.C)]);
    expect((await service.teamState(id)).score).toBe(45);
    expect((await service.teamState(id)).current).toBe(2);
    expect(await db.submission.count({ where: { teamId: id, chapter: 1, accepted: true } })).toBe(1);
  });
});
